export function isQrModuleDark(row: number, col: number): boolean {
  return QR_ROWS[row][col] === '1';
}

// Los 3 patrones "ojo" (buscador), 7x7 módulos en tres esquinas — su
// proporción exacta es lo que un lector usa para orientarse, así que se
// dibujan como cuadrados normales, sin redondear cada módulo por separado.
export function isQrFinderArea(row: number, col: number): boolean {
  const inTL = col < 7 && row < 7;
  const inTR = col >= QR_SIZE - 7 && row < 7;
  const inBL = col < 7 && row >= QR_SIZE - 7;
  return inTL || inTR || inBL;
}
